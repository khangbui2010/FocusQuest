export class AppError extends Error {
  readonly code: ErrorCode;
  readonly params?: ErrorParams;

  constructor(code: ErrorCode, message: string, params?: ErrorParams) {
    super(message);
    this.name = 'AppError';
    this.code = code;
    this.params = params;
  }
}

export interface CodedErrorLike {
  code?: string;
  params?: ErrorParams;
  message?: string;
}

export function extractCodedError(err: unknown): CodedErrorLike {
  if (err && typeof err === 'object') {
    const candidate = err as { code?: unknown; params?: unknown; message?: unknown };
    return {
      code: typeof candidate.code === 'string' ? candidate.code : undefined,
      params:
        candidate.params && typeof candidate.params === 'object'
          ? (candidate.params as ErrorParams)
          : undefined,
      message: typeof candidate.message === 'string' ? candidate.message : String(err),
    };
  }
  return {
    message: typeof err === 'string' ? err : String(err),
  };
}
