/**
 * Maps construction progress to a stage index 0..3.
 * progress = 1 - remaining / total (clamped to [0, 1)); 1 means complete and uses the finished sprite.
 */
export function getConstructionStageIndex(remaining: number, total: number): number {
  if (!Number.isFinite(remaining) || !Number.isFinite(total) || total <= 0) {
    return 0;
  }
  const progress = Math.min(Math.max(1 - remaining / total, 0), 0.999999);
  return Math.min(CONSTRUCTION_STAGE_COUNT - 1, Math.floor(progress * CONSTRUCTION_STAGE_COUNT));
}

/**
 * Resolves the under-construction PixelSpriteMatrix for a building definition at the given
 * remaining / total progress, or null if the building has no construction sprite (e.g. Campfire).
 */
export function getConstructionSprite(
  definitionId: string,
  remaining: number,
  total: number
): PixelSpriteMatrix | null {
  const stages = CONSTRUCTION_SPRITE_STAGES[definitionId];
  if (!stages || stages.length === 0) {
    return null;
  }
  const idx = getConstructionStageIndex(remaining, total);
  return stages[Math.min(stages.length - 1, Math.max(0, idx))] ?? stages[0];
}

