export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

export type LocalizableError =
  | string
  | {
      message?: string | null;
      error?: string | null;
      errorCode?: string | null;
      errorParams?: ErrorParams | null;
      code?: string | null;
      params?: ErrorParams | null;
    };

export class CodedError extends Error {
  readonly code: ErrorCode;
  readonly errorCode: ErrorCode;
  readonly params?: ErrorParams;
  readonly errorParams?: ErrorParams;

  constructor(code: ErrorCode, message: string, params?: ErrorParams) {
    super(message);
    this.name = 'CodedError';
    this.code = code;
    this.errorCode = code;
    this.params = params;
    this.errorParams = params;
  }
}

export function extractErrorDetails(error: unknown): {
  message: string;
  errorCode?: string;
  errorParams?: ErrorParams;
} {
  if (error instanceof CodedError) {
    return {
      message: error.message,
      errorCode: error.code,
      errorParams: error.params,
    };
  }
  if (error && typeof error === 'object') {
    const obj = error as Record<string, unknown>;
    const rawMsg =
      typeof obj.message === 'string'
        ? obj.message
        : typeof obj.error === 'string'
        ? obj.error
        : '';
    const code =
      typeof obj.errorCode === 'string'
        ? obj.errorCode
        : typeof obj.code === 'string'
        ? obj.code
        : undefined;
    const rawParams = obj.errorParams ?? obj.params;
    const errorParams =
      rawParams && typeof rawParams === 'object' && !Array.isArray(rawParams)
        ? (rawParams as ErrorParams)
        : undefined;
    return { message: rawMsg, errorCode: code, errorParams };
  }
  return {
    message: error instanceof Error ? error.message : typeof error === 'string' ? error : String(error ?? ''),
  };
}

export function toCodedError(
  res: { error?: string; errorCode?: string; errorParams?: ErrorParams } | null | undefined,
  fallbackCode: ErrorCode,
  fallbackMessage: string
): CodedError {
  const code = (res?.errorCode as ErrorCode | undefined) || fallbackCode;
  const message = res?.error || fallbackMessage;
  return new CodedError(code, message, res?.errorParams);
}
